import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MAX_RECORD_CHARS = 100 * 1024 * 1024;

function sqlText(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function stableRecordId(collection, record) {
  const known = record?.id ?? record?.userId ?? record?.streamId ?? record?.tokenHash;
  if (known !== undefined && known !== null && String(known)) return String(known);
  return `legacy_${createHash('sha256').update(JSON.stringify(record)).digest('hex').slice(0, 32)}`;
}

/**
 * Produces a repeatable import snapshot for stream24_records.
 * Run the schema migration first; this function never connects to or mutates a database.
 */
export function generatePostgresImportSql(db) {
  if (!db || typeof db !== 'object' || Array.isArray(db)) {
    throw new TypeError('Expected a JSON object containing collection arrays.');
  }
  const lines = [
    '-- Generated by scripts/export-json-to-postgres.mjs. Review before applying.',
    '-- Requires db/migrations/001_postgres_foundation.sql to be applied first.',
    'BEGIN;',
  ];
  let rowCount = 0;
  for (const collection of Object.keys(db).sort()) {
    const rows = db[collection];
    if (!Array.isArray(rows)) continue;
    if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(collection)) {
      throw new Error(`Invalid collection name: ${collection}`);
    }
    for (const record of rows) {
      if (!record || typeof record !== 'object' || Array.isArray(record)) {
        throw new TypeError(`Collection ${collection} contains a non-object record.`);
      }
      const id = stableRecordId(collection, record);
      const ownerId = record.ownerId ?? record.userId ?? null;
      const payload = JSON.stringify(record);
      if (payload.length > MAX_RECORD_CHARS) {
        throw new Error(`Record in ${collection} is too large for a safe migration snapshot.`);
      }
      lines.push(
        'INSERT INTO stream24_records (collection, record_id, owner_id, payload, updated_at) VALUES (' +
        `${sqlText(collection)}, ${sqlText(id)}, ${ownerId === null ? 'NULL' : sqlText(ownerId)}, ${sqlText(payload)}::jsonb, now()) ` +
        'ON CONFLICT (collection, record_id) DO UPDATE SET owner_id = EXCLUDED.owner_id, payload = EXCLUDED.payload, updated_at = now();'
      );
      rowCount++;
    }
  }
  lines.push('COMMIT;', `-- Imported ${rowCount} records across JSON collections.`, '');
  return lines.join('\n');
}

function main() {
  const input = path.resolve(process.argv[2] || path.join(ROOT, 'data', 'db.json'));
  const output = path.resolve(process.argv[3] || path.join(ROOT, 'data', 'postgres-import.sql'));
  if (!fs.existsSync(input)) {
    throw new Error(`Input JSON store not found: ${input}. Pass the path to your db.json as the first argument.`);
  }
  const db = JSON.parse(fs.readFileSync(input, 'utf8'));
  const sql = generatePostgresImportSql(db);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, sql, { encoding: 'utf8', mode: 0o600 });
  const count = (sql.match(/^INSERT INTO stream24_records/gm) || []).length;
  console.log(`Wrote ${count} record imports to ${output}`);
  console.log('This only generates a SQL file. Review it, back up the source, apply the schema, then import manually with psql.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
